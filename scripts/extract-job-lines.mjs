/**
 * Regenerates the job-posting test fixtures from a local folder of PDFs.
 *
 * The parser's strongest signal is typography, so a fixture has to carry
 * geometry - plain text is not enough any more. This writes the same line model
 * `extractJobDocument()` produces (page, y, font size, weight, text) as JSON:
 * reviewable in a diff, and still no binary blobs in the repo.
 *
 * Personal data is pseudonymized on the way out. The ads themselves are
 * published publicly and their employer names are needed for the assertions,
 * but the named contact people are not ours to check in.
 *
 * Usage:  node scripts/extract-job-lines.mjs <pdf-dir> [out-dir]
 * Not part of CI - fixtures are committed, this only refreshes them.
 */
import fs from 'node:fs';
import path from 'node:path';

const pdfjs = await import('pdfjs-dist/legacy/build/pdf.mjs');

const pdfDir = process.argv[2] ?? 'test-results/pdfs';
const outDir = process.argv[3] ?? 'src/lib/utils/fixtures/job-postings';

/** Real name -> stand-in. Applied to every line, so a name that also appears in
 *  a salutation or an e-mail stays consistent across the fixture. */
const NAME_REPLACEMENTS = [
	[/Laura\s+Steinbeisser/g, 'Petra Musterfrau'],
	[/Anton\s+Grabow/g, 'Anton Mustermann'],
	[/Marcel\s+Pfeiffer/g, 'Marcel Musterberg']
];

/** Phone numbers are kept structurally identical (prefix, grouping, length) so
 *  the phone heuristics are still exercised, but the digits are invented. */
const PHONE_REPLACEMENTS = [
	[/\+49\s*9903-6280\s*408/g, '+49 9900-1230 456'],
	[/\+49\s*351\s*65324737/g, '+49 351 12345678']
];

function pseudonymize(text) {
	let out = text;
	for (const [pattern, replacement] of [...NAME_REPLACEMENTS, ...PHONE_REPLACEMENTS]) {
		out = out.replace(pattern, replacement);
	}
	return out;
}

/** Mirrors extractJobDocument() in src/lib/utils/pdf.ts - keep the two in sync. */
async function extractLines(data) {
	const pdf = await pdfjs.getDocument({ data }).promise;
	const lines = [];

	for (let pageNum = 1; pageNum <= pdf.numPages; pageNum++) {
		const page = await pdf.getPage(pageNum);
		const content = await page.getTextContent();
		const styles = content.styles ?? {};
		let current = null;
		let lastY = null;

		const flush = () => {
			if (!current) return;
			const text = current.parts.join(' ').replace(/\s+/g, ' ').trim();
			if (text) {
				lines.push({
					page: pageNum,
					y: current.y,
					size: current.size,
					bold: current.bold,
					text: pseudonymize(text)
				});
			}
			current = null;
		};

		for (const item of content.items) {
			if (typeof item.str !== 'string') continue;
			const value = item.str.trim();
			if (!value) {
				if (item.hasEOL) flush();
				continue;
			}
			if (!item.transform || item.transform.length < 6) continue;

			const y = Math.round(item.transform[5]);
			const size = Math.round(Math.hypot(item.transform[2], item.transform[3]) * 10) / 10;
			const fontFamily = item.fontName ? (styles[item.fontName]?.fontFamily ?? '') : '';
			const bold = /bold|black|heavy|semibold/i.test(fontFamily);

			if (current && lastY !== null && Math.abs(lastY - y) > 5) flush();

			if (!current) {
				current = { y, size, bold, parts: [value] };
			} else {
				current.parts.push(value);
				current.size = Math.max(current.size, size);
				current.bold = current.bold || bold;
			}

			lastY = y;
			if (item.hasEOL) flush();
		}

		flush();
	}

	return { lines, pageCount: pdf.numPages };
}

function slugify(name) {
	return name
		.replace(/\.pdf$/i, '')
		.toLowerCase()
		.replace(/[^a-z0-9]+/g, '-')
		.replace(/^-+|-+$/g, '')
		.slice(0, 60);
}

fs.mkdirSync(outDir, { recursive: true });

const files = fs.readdirSync(pdfDir).filter((name) => name.toLowerCase().endsWith('.pdf'));
if (files.length === 0) {
	console.error(`No PDFs found in ${pdfDir}`);
	process.exit(1);
}

for (const file of files) {
	const data = new Uint8Array(fs.readFileSync(path.join(pdfDir, file)));
	const { lines, pageCount } = await extractLines(data);
	const slug = slugify(file);
	const payload = {
		source: file.replace(/[^\w\s.()-]/g, ''),
		note: 'Pseudonymized fixture generated by scripts/extract-job-lines.mjs. Contact-person names and phone numbers are invented; employer names and ad text are from a publicly published vacancy.',
		pageCount,
		lines
	};
	const out = path.join(outDir, `${slug}.json`);
	fs.writeFileSync(out, JSON.stringify(payload, null, '\t') + '\n', 'utf8');
	console.log(`${out}  (${lines.length} lines, ${pageCount} pages)`);
}
